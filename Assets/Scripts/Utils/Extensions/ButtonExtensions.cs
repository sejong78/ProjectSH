using UnityEngine.UI;

public static class ButtonExtensions
{
	//@@-------------------------------------------------------------------------------------------------------------------------
	//@@-------------------------------------------------------------------------------------------------------------------------

	public static bool IsEnabled( this Button button, bool enable )
	{
		if( null == button )
		{
			return false;
		}

		button.interactable = enable;

		return enable;
	}

	//@@-------------------------------------------------------------------------------------------------------------------------
	//@@-------------------------------------------------------------------------------------------------------------------------

}//ButtonExtensions
