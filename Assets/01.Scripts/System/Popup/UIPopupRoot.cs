using UnityEngine;

/// <summary>
/// @class UIPopupRoot
/// @brief Popup을 생성해서 부붙일 Root 위치 지정
/// Hierarchy 에 "RootPopup" Tag 가 적용된 오브젝트가 필요하다.
/// </summary>
public class UIPopupRoot : MonoBehaviour
{
	//@@-------------------------------------------------------------------------------------------------------------------------
	//@@-------------------------------------------------------------------------------------------------------------------------

	private void Start()
	{
		PopupManager.RootGameObject = gameObject;

		transform.SetAsLastSibling();
	}

	//@@-------------------------------------------------------------------------------------------------------------------------

	private void OnDestroy()
	{
		PopupManager.RootGameObject = null;
	}

	//@@-------------------------------------------------------------------------------------------------------------------------
	//@@-------------------------------------------------------------------------------------------------------------------------
}//UIPopupRoot
