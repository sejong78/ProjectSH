/**---------------------------------------------------------------------------------
 * @file View_RailMap.cs
 * @brief 맵 서브신 루트 컴포넌트. 레일·바닥·기준물 등 월드 콘텐츠를 묶는 허브이며,
 *        런타임 로더가 RailPath를 추출해 카메라 앵커에 바인딩하는 진입점을 제공한다.
 *///-------------------------------------------------------------------------------
using UnityEngine;

/// <summary>
/// 맵(서브신)의 루트. 순수 월드 콘텐츠(RailPath + GridFloor + 베이크된 Markers)를 보유한다.
/// 카메라/앵커/캐릭터는 포함하지 않는다(별도 로드). 향후 장애물·장식 등을 자식으로 확장한다.
/// </summary>
public class View_RailMap : MonoBehaviour
{
    //@@-------------------------------------------------------------------------------------------------------------------------
    //@@-------------------------------------------------------------------------------------------------------------------------

    [Header( "맵 식별자" )]
    [SerializeField] private string _mapId = "Map_RailRunner";

    [Header( "월드 콘텐츠 참조" )]
    [SerializeField] private View_RailPath _railPath = null;

    /// <summary> 맵 식별자(로더 키/로그용). </summary>
    public string MapId { get { return _mapId; } }

    //@@-------------------------------------------------------------------------------------------------------------------------
    //@@-------------------------------------------------------------------------------------------------------------------------

    /// <summary>
    /// 맵의 레일. 미지정 시 자식에서 탐색해 캐싱한다.
    /// </summary>
    public View_RailPath RailPath
    {
        get
        {
            if( null == _railPath )
                _railPath = GetComponentInChildren<View_RailPath>( true );
            return _railPath;
        }
    }

    //@@-------------------------------------------------------------------------------------------------------------------------
    /// <summary>
    /// 레일 LUT를 보장한다. additive 로드 직후 안전하게 호출 가능.
    /// </summary>
    /// <returns>레일 준비 성공 여부.</returns>
    public bool EnsureReady()
    {
        View_RailPath rail = RailPath;
        if( null == rail )
        {
            DebugExtensions.LogError( $"[View_RailMap] '{_mapId}' RailPath 없음 → 준비 실패.", Color.red );
            return false;
        }

        if( false == rail.IsReady )
            rail.Rebuild();

        return rail.IsReady;
    }

    //@@-------------------------------------------------------------------------------------------------------------------------
    //@@-------------------------------------------------------------------------------------------------------------------------

}//View_RailMap
